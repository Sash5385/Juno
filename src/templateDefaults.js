export const defaultBody = id => POLITE[id]?.new ?? "";

// Замінює ЛИШЕ незмінені старі стандартні тексти на нові; усе інше (відредаговане) повертає як є.
// Ідемпотентна: другий запуск нічого не змінює.
export function migratePolite(list) {
  let changed = false;
  const out = list.map(t => {
    const p = t && POLITE[t.id];
    if (!p || typeof t.body !== "string" || !p.old.includes(t.body)) return t;
    changed = true;
    return { ...t, body: p.new };
  });
  return { list: out, changed };
}
